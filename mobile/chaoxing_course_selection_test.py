"""Exercise Chaoxing-only selection and native refresh without changing MOOC choices."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import sys
sys.stdout.reconfigure(encoding='utf-8')
root=Path(__file__).resolve().parent
with sync_playwright() as p:
 browser=p.chromium.launch(channel='msedge',headless=True)
 page=browser.new_page(viewport={'width':390,'height':844})
 page.goto((root/'assets/index.html').as_uri())
 page.locator('nav [data-page=settings]').click()
 assert page.locator('[data-select-platform-courses=chaoxing]').count()==1,'Chaoxing connection needs its own course selection entry'
 page.locator('[data-select-platform-courses=chaoxing]').click()
 expect(page.locator('#course-dialog')).to_be_visible()
 expect(page.locator('#course-dialog input[data-course]')).to_have_count(2)
 expect(page.locator('#course-dialog [data-course=mooc-math]')).to_have_count(0)
 expect(page.locator('#course-dialog h2')).to_contain_text('学习通')
 page.locator('#course-dialog [data-course-bulk=hide]').click()
 assert page.evaluate("state.courses.filter(c=>c.platform==='chaoxing').every(c=>c.enabled===false)")
 assert page.evaluate("state.courses.find(c=>c.key==='mooc-math').enabled!==false")
 expect(page.locator('#assignment-list [data-task=demo1]')).to_have_count(0)
 expect(page.locator('#assignment-list [data-task=demo4]')).to_have_count(0)
 expect(page.locator('#assignment-list [data-task=demo5]')).to_have_count(0)
 page.evaluate('onNativeState(JSON.stringify(state))')
 expect(page.locator('#course-dialog input[data-course]')).to_have_count(2)
 page.locator('#course-dialog [data-course=cx-ds]').check()
 expect(page.locator('#assignment-list [data-task=demo1]')).to_have_count(1)
 assert page.evaluate("state.courses.find(c=>c.key==='cx-eng').enabled===false")
 page.evaluate('window.calls=[];window.Native={action:(action,payload)=>calls.push({action,data:JSON.parse(payload)})}')
 page.locator('#course-dialog [data-course-bulk=show]').click()
 assert page.evaluate("calls.at(-1).action==='toggleCourses'&&calls.at(-1).data.enabled&&calls.at(-1).data.keys.length===2&&calls.at(-1).data.keys.every(k=>k.startsWith('cx-'))")
 page.locator('#close-courses').click()
 page.locator('[data-select-platform-courses=mooc]').click()
 expect(page.locator('#course-dialog input[data-course]')).to_have_count(1)
 page.locator('#course-dialog [data-course-bulk=hide]').click()
 assert page.evaluate("calls.at(-1).data.keys.join()==='mooc-math'")
 assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
 page.locator('#close-courses').click()
 page.locator('nav [data-page=tasks]').click()
 page.locator('[data-select-courses]').click()
 expect(page.locator('#course-dialog input[data-course]')).to_have_count(3)
 page.screenshot(path=str(root/'preview/学习通课程选择-示例.png'),full_page=True)
 browser.close()
print('Passed 18 Chaoxing/MOOC course selection checks.')
