"""Course choices apply to counts, every task view and the course picker."""
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
import sys
sys.stdout.reconfigure(encoding='utf-8')
root=Path(__file__).resolve().parent
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':390,'height':844})
    page.clock.install(time=1791511200)
    page.goto((root/'assets/index.html').as_uri())
    page.locator('#course-picker-button').click()
    page.locator('[data-pick-course=mooc-math]').click()
    page.locator('#course-picker-button').click();page.locator('#picker-management').click()
    page.locator('[data-course-expand=mooc]').click()
    page.locator('#course-dialog [data-course=mooc-math]').uncheck()
    expect(page.locator('#assignment-list [data-task=demo2]')).to_have_count(1) # draft not applied yet
    page.locator('#close-courses').click()
    assert page.locator('#course-filter').input_value()=='all'
    expect(page.locator('#count-week')).to_have_text('1')
    for task in ['demo2','demo3']:expect(page.locator(f'#assignment-list [data-task={task}]')).to_have_count(0)
    page.evaluate("state.tasks.find(t=>t.id==='demo2').status='done';render()")
    page.locator('#filter-button').click();page.locator('[data-filter=done]').click();page.locator('#apply-filters').click()
    expect(page.locator('#assignment-list [data-task=demo2]')).to_have_count(0)
    page.locator('nav [data-page=calendar]').click()
    assert '高等数学' not in page.locator('#day-list').inner_text()
    page.locator('nav [data-page=tasks]').click()
    page.locator('#course-picker-button').click()
    expect(page.locator('[data-pick-course=mooc-math]')).to_have_count(0)
    page.locator('#picker-management').click();page.locator('[data-course-expand=mooc]').click()
    page.locator('#course-dialog [data-course=mooc-math]').check();page.locator('#close-courses').click()
    page.locator('#filter-button').click();page.locator('[data-filter=all]').click();page.locator('#apply-filters').click()
    for task in ['demo2','demo3']:expect(page.locator(f'#assignment-list [data-task={task}]')).to_have_count(1)
    page.evaluate('onNativeState(JSON.stringify(state))')
    page.locator('#course-picker-button').click();page.locator('#picker-management').click()
    for platform in ['mooc','chaoxing']:
        page.locator(f'[data-course-expand={platform}]').click()
        page.locator(f'[data-course-bulk=hide][data-scope={platform}]').click()
    page.locator('#close-courses').click()
    expect(page.locator('#assignment-list .assignment-card')).to_have_count(0)
    expect(page.locator('#count-week')).to_have_text('0')
    page.locator('#undo-courses').click()
    expect(page.locator('#assignment-list .assignment-card')).to_have_count(5)
    page.locator('#course-picker-button').click();page.locator('#picker-management').click()
    page.screenshot(path=str(root/'preview/选择课程-示例.png'),full_page=False)
    page.locator('#cancel-courses').click()
    expect(page.locator('#course-dialog')).to_be_hidden()
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth')
    browser.close()
print('Passed course visibility, draft application, all views, picker, counts, refresh and undo checks.')
