"""Replay course selection across all task views, including refreshed native state."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import sys
sys.stdout.reconfigure(encoding='utf-8')
root=Path(__file__).resolve().parent
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    page=browser.new_page(viewport={'width':390,'height':844})
    page.goto((root/'assets/index.html').as_uri())
    page.locator('#filter-button').click()
    page.locator('#course-filter').select_option('mooc-math')
    page.locator('nav [data-page=settings]').click()
    page.locator('#course-settings [data-course=mooc-math]').uncheck()
    assert page.locator('#course-filter').input_value()=='all'
    expect(page.locator('#count-week')).to_have_text('1')
    page.locator('nav [data-page=tasks]').click()
    page.locator('[data-filter=all]').click()
    expect(page.locator('#assignment-list [data-task=demo2]')).to_have_count(0)
    expect(page.locator('#assignment-list [data-task=demo3]')).to_have_count(0)
    page.evaluate("state.tasks.find(t=>t.id==='demo2').status='done';render()")
    page.locator('[data-filter=done]').click()
    expect(page.locator('#assignment-list [data-task=demo2]')).to_have_count(0)
    page.locator('nav [data-page=calendar]').click()
    assert not page.evaluate("document.querySelector('#day-list').innerText.includes('高等数学')")
    expect(page.locator('#course-filter option[value=mooc-math]')).to_have_count(0)
    page.evaluate('onNativeState(JSON.stringify(state))')
    page.locator('nav [data-page=tasks]').click()
    page.locator('[data-filter=all]').click()
    expect(page.locator('#assignment-list [data-task=demo2]')).to_have_count(0)
    page.locator('nav [data-page=settings]').click()
    page.locator('#course-settings [data-course=mooc-math]').check()
    page.locator('nav [data-page=tasks]').click()
    expect(page.locator('#assignment-list [data-task=demo2]')).to_have_count(1)
    expect(page.locator('#assignment-list [data-task=demo3]')).to_have_count(1)
    page.locator('[data-select-courses]').click()
    expect(page.locator('#course-dialog')).to_be_visible()
    page.locator('#course-dialog [data-course-bulk=hide]').click()
    expect(page.locator('#assignment-list .assignment-card')).to_have_count(0)
    expect(page.locator('#count-week')).to_have_text('0')
    page.locator('#course-dialog [data-course-bulk=show]').click()
    expect(page.locator('#assignment-list .assignment-card')).to_have_count(5)
    assert page.evaluate('document.documentElement.scrollWidth <= window.innerWidth')
    page.screenshot(path=str(root/'preview/选择课程-示例.png'),full_page=True)
    page.locator('#close-courses').click()
    expect(page.locator('#course-dialog')).to_be_hidden()
    browser.close()
print('Passed 16 course visibility checks.')
